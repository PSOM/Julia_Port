#!/bin/bash
# Grid-size override for validation runs (source this file).
#
#   PSOM_SIZE="NI NJ NK ngrid"   e.g. PSOM_SIZE="16 192 96 4"
#
# The multigrid storage sizes (maxout, maxint, int1) are derived the same way as in mgrid:
#   level m has nx=NI/2^(m-1) (etc.); maxout = sum (nx+2)(ny+2)(nz+2), maxint = sum nx*ny*nz,
#   int1 = NI*NJ*NK.
# Used so that large experiments (e.g. waves, whose static Fortran arrays exceed 2 GB and cannot be
# linked on macOS) can be validated on a smaller grid with identical code.

size_suffix() { if [ -n "$PSOM_SIZE" ]; then echo "_$(echo $PSOM_SIZE | awk '{print $1"x"$2"x"$3"g"$4}')"; fi; return 0; }

size_params() {   # prints: NI NJ NK ngrid maxout maxint int1
    echo $PSOM_SIZE | awk '{
        ni=$1; nj=$2; nk=$3; ng=$4; mo=0; mi=0
        for (m=1; m<=ng; m++) {
            if (ni%1 || nj%1 || nk%1) { print "bad size" > "/dev/stderr"; exit 1 }
            mo += (ni+2)*(nj+2)*(nk+2); mi += ni*nj*nk
            if (m<ng && (ni%2 || nj%2 || nk%2)) { print "grid not divisible by 2 at level " m > "/dev/stderr"; exit 1 }
            ni/=2; nj/=2; nk/=2
        }
        print $1, $2, $3, ng, mo, mi, $1*$2*$3 }'
}

write_size_h() {  # $1 = file
    read NI NJ NK NG MO MI I1 <<< "$(size_params)"
    cat > "$1" <<EOF
! generated by validation/size_override.sh (PSOM_SIZE="$PSOM_SIZE")
INTEGER, PARAMETER :: ntr = 1, nconsume = 1
INTEGER,PARAMETER :: NI=$NI, NJ=$NJ, NK=$NK, ngrid=$NG, maxout=$MO, maxint=$MI, int1=$I1
EOF
}

write_size_jl() { # $1 = file
    read NI NJ NK NG MO MI I1 <<< "$(size_params)"
    cat > "$1" <<EOF
# generated by validation/size_override.sh (PSOM_SIZE="$PSOM_SIZE")
global const ntr = 1
global const nconsume = 1

global const NI=$NI
global const NJ=$NJ
global const NK=$NK
global const ngrid=$NG
global const maxout=$MO
global const maxint=$MI
global const int1=$I1
EOF
}
